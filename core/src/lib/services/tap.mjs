import { readFile, writeFile } from '#shared/fs'
import { ensureServiceCertificate } from '#lib/tls'
import { hash } from '#shared/crypto'
// Default hooks
import { defaultRecreateServiceHook, defaultRestartServiceHook } from './index.mjs'
// utils
import { utils } from '../utils.mjs'
import { autoGeneratedHeader } from './core.mjs'
import { isTapWanted } from '../tap.mjs'

/**
 * Service object holds the various lifecycle hook methods
 */
export const service = {
  name: 'tap',
  hooks: {
    /**
     * Lifecycle hook to determine whether the container is wanted
     *
     * @return {boolean} wanted - Wanted or not
     */
    wanted: () => {
      if (utils.isEphemeral()) return false
      if (isTapWanted()) {
        /*
         * We need a tap service, but where do we run it?
         * Do we have a specific tap node in the settings?
         */
        const tNodes = utils.getSettings('flanking_services.tap.nodes', [])
        if (tNodes.includes(utils.getNodeFqdn())) {
          // FIXME: This should not run here, right?
          // ensureLocalPrerequisites()
          return true
        }
        /*
         * If there are explicit nodes, we are not part of them.
         * So do not run this service.
         */
        if (tNodes.length > 0) return false
        /*
         * No explicit tap node configured.
         * We will run it on all flanking nodes, or all broker nodes.
         */
        if (utils.getFlankingCount() > 0) {
          if (utils.isFlankingNode()) {
            // FIXME: This should not run here, right?
            // ensureLocalPrerequisites()
            return true
          }
        } else {
          // FIXME: This should not run here, right?
          // ensureLocalPrerequisites()
          return true
        }
      }

      return false
    },
    /*
     * Lifecycle hook to determine whether to recreate the container
     * We just reuse the default hook here, checking for changes in
     * name/version of the container.
     */
    recreate: () => defaultRecreateServiceHook('tap'),
    /**
     * Lifecycle hook to determine whether to restart the container
     * We just reuse the default hook here, checking whether the container
     * was recreated or is not running.
     */
    restart: (hookParams) => defaultRestartServiceHook('tap', hookParams),
    /**
     * Lifecycle hook for anything to be done prior to creating the container
     *
     * Write out the config file for tap as it will be volume-mapped,
     * so we need to write it to disk first so it's available
     */
    precreate: ensureLocalPrerequisites,
  },
}

async function ensureLocalPrerequisites() {
  /*
   * Generate key and certificate for mTLS
   * (this will only renew the cert if it's missing or old
   */
  await ensureServiceCertificate('tap', false)

  /*
   * Generate the tap config file
   */
  const keys = utils.getKeys()
  const localCache = utils.getCacheNode() === utils.getNodeFqdn()
  const config = {
    kafka: {
      clientId: 'morio-tap',
      brokers: [
        `${utils.getBrokerFqdns()}:${utils.getPreset('MORIO_BROKER_KAFKA_API_EXTERNAL_PORT')}`,
      ],
      ssl: {
        rejectUnauthorized: false,
        ca: await readFile('/etc/morio/tap/tls-ca.pem'),
        key: await readFile('/etc/morio/tap/tls-key.pem'),
        cert: await readFile('/etc/morio/tap/tls-cert.pem'),
      },
    },
    redis: {
      db: 0,
      family: 4,
      lazyConnect: true,
      connectionName: `morio.tap.${utils.getNodeUuid()}`,
      username: 'tap',
      password: [keys.mrt.hash, keys.private]
        .map((s) => hash(s + 'tap'))
        .join('')
        .slice(10, 42),
      host: localCache ? 'morio-cache.internal' : utils.getCacheNode(),
      port: localCache ? 6379 : 6661,
      tls: localCache
        ? false
        : {
            rejectUnauthorized: false,
            ca: [keys.icrt, keys.rcert],
          },
    },
    tap: {
      settings: utils.getSettings('tap.settings'),
      imports: utils.getSettings('tap.imports'),
    },
  }

  /*
   * Write the tap config file to disk
   */
  await writeFile(
    `/etc/morio/tap/tap.mjs`,
    [
      autoGeneratedHeader,
      '// Tap config',
      `export const config = ${JSON.stringify(config, null, 2)}`,
      '',
      '// Node info',
      `export const node = ${JSON.stringify(
        {
          ...utils.getNode(),
          cluster: utils.getClusterFqdn(),
        },
        null,
        2
      )}`,
    ].join('\n')
  )

  return
}
